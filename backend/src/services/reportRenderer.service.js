const PDFDocument = require('pdfkit');
const ExcelJS = require('exceljs');

// Every generated report / certificate is a plain "document" object:
// {
//   title, subtitle, meta: [[label, value]],
//   sections: [{ heading, kv?: [[label, value]], table?: { columns: [..], rows: [[..]] },
//                paragraphs?: [text], signatures?: [label] }]
// }
// Builders produce it, it's stored on the Report, and these renderers turn it into PDF / XLSX.

const MARGIN = 50;
const text = (v) => (v === undefined || v === null || v === '' ? '-' : String(v));

// ---------- PDF ----------

const pdfTable = (pdf, { columns, rows }) => {
  const width = pdf.page.width - MARGIN * 2;
  const colWidth = width / columns.length;
  const bottom = () => pdf.page.height - MARGIN;

  const drawRow = (cells, { bold = false } = {}) => {
    pdf.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(8.5);
    const heights = cells.map((c) => pdf.heightOfString(text(c), { width: colWidth - 6 }));
    const height = Math.max(...heights) + 6;
    if (pdf.y + height > bottom()) {
      pdf.addPage();
      if (!bold) drawRow(columns, { bold: true }); // repeat header on new page
      pdf.font('Helvetica').fontSize(8.5);
    }
    const y = pdf.y;
    if (bold) pdf.rect(MARGIN, y, width, height).fill('#eef1f6').fillColor('#000');
    cells.forEach((c, i) => pdf.text(text(c), MARGIN + i * colWidth + 3, y + 3, { width: colWidth - 6 }));
    pdf.moveTo(MARGIN, y + height).lineTo(MARGIN + width, y + height).strokeColor('#d0d5dd').lineWidth(0.5).stroke();
    pdf.x = MARGIN;
    pdf.y = y + height;
  };

  drawRow(columns, { bold: true });
  if (!rows.length) drawRow(['No records', ...columns.slice(1).map(() => '')]);
  rows.forEach((r) => drawRow(r));
  pdf.moveDown(0.8);
};

const pdfKv = (pdf, kv) => {
  const labelWidth = 190;
  kv.forEach(([k, v]) => {
    const y = pdf.y;
    pdf.font('Helvetica-Bold').fontSize(9.5).text(text(k), MARGIN, y, { width: labelWidth - 10 });
    const afterLabel = pdf.y;
    pdf.font('Helvetica').text(text(v), MARGIN + labelWidth, y, { width: pdf.page.width - MARGIN * 2 - labelWidth });
    pdf.x = MARGIN;
    pdf.y = Math.max(afterLabel, pdf.y) + 3;
  });
  pdf.moveDown(0.6);
};

// Returns a readable stream; pipe it to an HTTP response or a file
const renderPdf = (doc) => {
  const pdf = new PDFDocument({ margin: MARGIN, size: 'A4', info: { Title: doc.title } });

  pdf.font('Helvetica-Bold').fontSize(16).text(doc.title, { align: 'center' });
  if (doc.subtitle) pdf.font('Helvetica').fontSize(11).fillColor('#444').text(doc.subtitle, { align: 'center' }).fillColor('#000');
  pdf.moveDown(1);
  if (doc.meta?.length) pdfKv(pdf, doc.meta);

  doc.sections.forEach((section) => {
    if (pdf.y > pdf.page.height - 140) pdf.addPage();
    pdf.font('Helvetica-Bold').fontSize(12).fillColor('#1d3b6e').text(section.heading).fillColor('#000');
    pdf.moveDown(0.4);
    if (section.paragraphs) {
      section.paragraphs.forEach((p) => pdf.font('Helvetica').fontSize(10).text(p, { align: 'justify' }).moveDown(0.5));
    }
    if (section.kv) pdfKv(pdf, section.kv);
    if (section.table) pdfTable(pdf, section.table);
    if (section.signatures) {
      pdf.moveDown(3);
      const w = (pdf.page.width - MARGIN * 2) / section.signatures.length;
      const y = pdf.y;
      section.signatures.forEach((s, i) => {
        pdf.moveTo(MARGIN + i * w + 10, y).lineTo(MARGIN + (i + 1) * w - 10, y).strokeColor('#000').stroke();
        pdf.font('Helvetica').fontSize(9).text(s, MARGIN + i * w, y + 4, { width: w, align: 'center' });
      });
      pdf.x = MARGIN;
      pdf.moveDown(2);
    }
  });

  pdf.font('Helvetica').fontSize(7.5).fillColor('#888')
    .text(`Generated by Toolkit on ${new Date().toLocaleString('en-IN')}`, MARGIN, pdf.y + 10, { align: 'right' });
  pdf.end();
  return pdf;
};

// ---------- XLSX ----------

const sheetName = (name, used) => {
  const base = name.replace(/[\\/?*[\]:]/g, ' ').slice(0, 28) || 'Sheet';
  let candidate = base;
  for (let i = 2; used.has(candidate); i += 1) candidate = `${base.slice(0, 25)} ${i}`;
  used.add(candidate);
  return candidate;
};

// Returns a Buffer. Summary sheet = title + all key/value sections; one sheet per table.
const renderXlsx = async (doc) => {
  const wb = new ExcelJS.Workbook();
  wb.creator = 'Toolkit';
  const used = new Set();

  const summary = wb.addWorksheet(sheetName('Summary', used));
  summary.columns = [{ width: 38 }, { width: 60 }];
  summary.addRow([doc.title]).font = { bold: true, size: 14 };
  if (doc.subtitle) summary.addRow([doc.subtitle]);
  summary.addRow([]);
  (doc.meta || []).forEach(([k, v]) => summary.addRow([k, text(v)]));

  doc.sections.forEach((section) => {
    if (section.kv || section.paragraphs) {
      summary.addRow([]);
      summary.addRow([section.heading]).font = { bold: true, size: 12 };
      (section.paragraphs || []).forEach((p) => summary.addRow([p]));
      (section.kv || []).forEach(([k, v]) => {
        const row = summary.addRow([k, text(v)]);
        row.getCell(1).font = { bold: true };
      });
    }
    if (section.table) {
      const ws = wb.addWorksheet(sheetName(section.heading, used));
      const header = ws.addRow(section.table.columns);
      header.font = { bold: true };
      header.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFEEF1F6' } };
      section.table.rows.forEach((r) => ws.addRow(r.map((c) => (typeof c === 'number' ? c : text(c)))));
      ws.columns.forEach((col, i) => {
        const longest = Math.max(...[section.table.columns, ...section.table.rows].map((r) => text(r[i]).length));
        col.width = Math.min(Math.max(longest + 2, 10), 60);
      });
      ws.views = [{ state: 'frozen', ySplit: 1 }];
    }
  });

  return wb.xlsx.writeBuffer();
};

module.exports = { renderPdf, renderXlsx };
